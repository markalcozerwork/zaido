-- =============================================================================
-- Structural invariants of the schema (a lightweight Supabase-linter subset).
-- =============================================================================
\set ON_ERROR_STOP 1
reset role;

select tests.eq(
  (select string_agg(c.relname, ', ') from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' and not c.relrowsecurity),
  null, 'every public table has RLS enabled');

select tests.eq(
  (select string_agg(c.relname, ', ') from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
      and not exists (select 1 from pg_constraint k where k.conrelid = c.oid and k.contype = 'p')),
  null, 'every public table has a primary key');

-- Range-type constructors are generated by Postgres and carry no search_path.
select tests.eq(
  (select string_agg(n.nspname || '.' || p.proname, ', ')
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'app') and p.prokind = 'f'
      and p.prorettype not in ('public.timerange'::regtype, 'public.timemultirange'::regtype)
      and not exists (select 1 from unnest(p.proconfig) cfg where cfg like 'search_path=%')),
  null, 'every function pins search_path');

select tests.eq(
  (select string_agg(n.nspname || '.' || p.proname, ', ')
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'app') and p.prosecdef
      and has_function_privilege('public', p.oid, 'execute')),
  null, 'no SECURITY DEFINER function is executable by PUBLIC');

select tests.ok(not has_function_privilege('anon', 'public.get_or_create_direct_channel(uuid)', 'execute'),
                'anon cannot open DM channels');
select tests.ok(not has_function_privilege('authenticated', 'app.complete_finished_bookings()', 'execute'),
                'end users cannot run maintenance jobs');

select tests.eq(
  (select string_agg(format('%s.%s', c.relname, a.attname), ', ')
     from pg_class c join pg_attribute a on a.attrelid = c.oid
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
      and a.attnum > 0 and not a.attisdropped
      and a.atttypid in ('timestamp'::regtype, 'json'::regtype, 'real'::regtype, 'double precision'::regtype, 'money'::regtype)),
  null, 'no naive timestamps, json (use jsonb), floats or money types');

select tests.ok(exists (select 1 from pg_constraint where conname = 'bookings_no_court_overlap' and contype = 'x'),
                'court double-booking exclusion constraint present');
select tests.ok(has_table_privilege('authenticated', 'public.bookings', 'insert')
                and not has_table_privilege('authenticated', 'public.bookings', 'delete')
                and not has_table_privilege('authenticated', 'public.bookings', 'truncate'),
                'bookings: insert yes, delete/truncate never');
