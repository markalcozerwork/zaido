-- =============================================================================
-- Structural invariants of the schema (a lightweight Supabase-linter subset).
-- =============================================================================
\set ON_ERROR_STOP 1
reset role;

select tests.eq(
  (select string_agg(c.relname, ', ') from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' and not c.relrowsecurity),
  null, 'every public table has RLS enabled');

select tests.eq(
  (select string_agg(c.relname, ', ') from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
      and not exists (select 1 from pg_constraint k where k.conrelid = c.oid and k.contype = 'p')),
  null, 'every public table has a primary key');

-- Range-type constructors are generated by Postgres and carry no search_path.
select tests.eq(
  (select string_agg(n.nspname || '.' || p.proname, ', ')
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'app') and p.prokind = 'f'
      and p.prorettype not in ('public.timerange'::regtype, 'public.timemultirange'::regtype)
      and not exists (select 1 from unnest(p.proconfig) cfg where cfg like 'search_path=%')),
  null, 'every function pins search_path');

select tests.eq(
  (select string_agg(n.nspname || '.' || p.proname, ', ')
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'app') and p.prosecdef
      and has_function_privilege('public', p.oid, 'execute')),
  null, 'no SECURITY DEFINER function is executable by PUBLIC');

select tests.ok(not has_function_privilege('anon', 'public.get_or_create_direct_channel(uuid)', 'execute'),
                'anon cannot open DM channels');
select tests.ok(not has_function_privilege('authenticated', 'app.complete_finished_bookings()', 'execute'),
                'end users cannot run maintenance jobs');

select tests.eq(
  (select string_agg(format('%s.%s', c.relname, a.attname), ', ')
     from pg_class c join pg_attribute a on a.attrelid = c.oid
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
      and a.attnum > 0 and not a.attisdropped
      and a.atttypid in ('timestamp'::regtype, 'json'::regtype, 'real'::regtype, 'double precision'::regtype, 'money'::regtype)),
  null, 'no naive timestamps, json (use jsonb), floats or money types');

select tests.ok(exists (select 1 from pg_constraint where conname = 'bookings_no_court_overlap' and contype = 'x'),
                'court double-booking exclusion constraint present');
select tests.ok(has_table_privilege('authenticated', 'public.bookings', 'insert')
                and not has_table_privilege('authenticated', 'public.bookings', 'delete')
                and not has_table_privilege('authenticated', 'public.bookings', 'truncate'),
                'bookings: insert yes, delete/truncate never');

-- Step 3 ------------------------------------------------------------------------
select tests.eq(
  (select string_agg(p.proname, ', ' order by p.proname)
     from pg_proc p
    where p.pronamespace = 'public'::regnamespace
      and has_function_privilege('anon', p.oid, 'execute')
      and p.prorettype not in ('public.timerange'::regtype, 'public.timemultirange'::regtype)
      and p.proname not in ('get_court_busy_slots', 'get_venue_busy_slots', 'get_coach_busy_slots', 'quote_court_booking')),
  null, 'anon can execute only the allow-listed public RPCs');

select tests.ok(not (select prosecdef from pg_proc where oid = 'public.create_booking'::regproc),
                'create_booking stays SECURITY INVOKER (a DEFINER version would bypass every guard rule)');
select tests.ok(not exists (select 1 from pg_proc p, unnest(p.proconfig) c
                             where p.oid = 'public.create_booking'::regproc and c ilike '%isolation%'),
                'create_booking runs at the caller''s isolation (its twin detection relies on READ COMMITTED)');
select tests.ok(not has_table_privilege('authenticated', 'app.coach_commitments', 'select')
                and not has_table_privilege('anon', 'app.coach_commitments', 'select'),
                'the coach ledger is not readable by API roles');
select tests.ok(to_regclass('realtime.messages') is null
                or exists (select 1 from pg_policies where schemaname = 'realtime' and tablename = 'messages'
                             and policyname = 'court slot topics are receivable'),
                'the court-slot receive policy exists wherever Realtime does');

select tests.eq(
  (select string_agg(t, ', ') from unnest(array[
      'bookings_guard', 'bookings_35_release_event', 'bookings_40_coach_commitments', 'bookings_50_broadcast_slots',
      'events_guard', 'events_30_reserve_booking', 'events_40_coach_commitments',
      'court_closures_stamp', 'court_closures_broadcast']) as t
    where not exists (select 1 from pg_trigger g where g.tgname = t and not g.tgisinternal)),
  null, 'booking-engine triggers are installed');

-- Step 4 ------------------------------------------------------------------------
select tests.eq(
  (select string_agg(t, ', ') from unnest(array[
      'chat_messages_10_guard', 'chat_messages_20_sequence', 'chat_messages_80_after',
      'chat_participants_10_defaults', 'chat_participants_20_guard', 'chat_participants_80_hints',
      'chat_channels_80_hints', 'chat_channels_81_deleted', 'chat_reports_resolve']) as t
    where not exists (select 1 from pg_trigger g where g.tgname = t and not g.tgisinternal)),
  null, 'chat-engine triggers are installed');
select tests.ok(not exists (select 1 from pg_trigger where tgname = 'chat_messages_touch_channel'),
                'the old touch-channel trigger is gone (its work moved under the channel lock)');
select tests.eq(
  (select string_agg(p.oid::regprocedure::text, ', ')
     from pg_proc p
    where p.oid in ('app.tg_chat_messages_guard'::regproc, 'app.tg_chat_participants_guard'::regproc,
                    'public.send_chat_message'::regproc, 'public.get_chat_messages'::regproc)
      and p.prosecdef),
  null, 'chat guards and the send/read RPCs stay SECURITY INVOKER (is_trusted_context() is true inside DEFINER code)');
select tests.ok((select prosecdef from pg_proc where oid = 'app.tg_chat_messages_sequence'::regproc),
                'the sequence trigger is SECURITY DEFINER (users cannot update chat_channels)');
select tests.ok(not exists (select 1 from pg_publication_tables
                             where pubname = 'supabase_realtime' and tablename in ('chat_messages', 'chat_participants')),
                'chat tables are not in the Postgres Changes publication');
select tests.ok(to_regclass('realtime.messages') is null
                or (select count(*) from pg_policies where schemaname = 'realtime' and tablename = 'messages'
                      and policyname in ('chat topics: members receive', 'chat typing: members send',
                                         'user chat topic: owner receives')) = 3,
                'the chat topic policies exist wherever Realtime does');
select tests.eq(
  (select string_agg(policyname, ', ') from pg_policies
    where schemaname = 'realtime' and tablename = 'messages' and cmd in ('INSERT', 'ALL')
      and policyname <> 'chat typing: members send'),
  null, 'typing is the only client-sendable Realtime topic');
select tests.eq(
  (select string_agg(c.relname || ':' || r, ', ')
     from pg_class c, unnest(array['anon', 'authenticated']) r
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
      and c.relname in ('profile_blocks', 'chat_reports')
      and has_table_privilege(r, c.oid, 'truncate')),
  null, 'new chat tables grant no TRUNCATE to API roles');
