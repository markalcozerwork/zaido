#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# Regenerate src/db/database.types.ts from the live database schema.
#
#   npm run db:types         write the file
#   npm run db:types:check   fail if the committed file is stale (CI)
#
# Source database: $DATABASE_URL. It defaults to the local Supabase stack
# (`supabase start`). The script always uses --db-url so local and CI output
# are byte-identical.
# -----------------------------------------------------------------------------
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/src/db/database.types.ts"
DB_URL="${DATABASE_URL:-postgresql://postgres:postgres@127.0.0.1:54322/postgres}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

{
  echo "// AUTO-GENERATED by scripts/gen-db-types.sh from supabase/migrations. Do not edit."
  echo "// Regenerate with: npm run db:types"
  "$ROOT/node_modules/.bin/supabase" gen types typescript --db-url "$DB_URL" --schema public 2>"$TMP/stderr" \
    || { cat "$TMP/stderr" >&2; exit 1; }
} >"$TMP/raw.ts"

"$ROOT/node_modules/.bin/prettier" --stdin-filepath "$OUT" <"$TMP/raw.ts" >"$TMP/formatted.ts"

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$OUT" "$TMP/formatted.ts"; then
    echo "✘ src/db/database.types.ts is out of date with the migrations. Run: npm run db:types" >&2
    exit 1
  fi
  echo "✔ database types are up to date"
else
  mkdir -p "$(dirname "$OUT")"
  mv "$TMP/formatted.ts" "$OUT"
  echo "✔ wrote ${OUT#"$ROOT"/}"
fi
